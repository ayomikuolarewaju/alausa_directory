export const isRecordStale = (lastReviewedAt?: string, now = new Date()) => {
  if (!lastReviewedAt) return true;
  const reviewedAt = Date.parse(lastReviewedAt);
  if (!Number.isFinite(reviewedAt)) return true;
  return now.getTime() - reviewedAt > 90 * 24 * 60 * 60 * 1000;
};

export const getEntityDescription = (entity: Entity) => {
  const details = [
    entity.description,
    entity.officers.find((officer) => officer.name.trim())?.name,
    entity.address,
    entity.phone && `Phone: ${entity.phone}`,
    entity.email && `Email: ${entity.email}`,
  ].filter(Boolean);

  return details.join(" ").slice(0, 160).trimEnd();
};

export const searchEntities = (query: string) => {
  return searchEntityList(entities, query);
};

export const searchEntityList = (records: Entity[], query: string) => {
  const q = query.toLowerCase();
  return records.filter(
    (e) =>
      e.name.toLowerCase().includes(q) ||
      e.description.toLowerCase().includes(q) ||
      e.location.toLowerCase().includes(q) ||
      e.officers.some((o) => o.name.toLowerCase().includes(q))
  );
};

